import { build } from 'esbuild';
import { mkdir, copyFile, cp } from 'node:fs/promises';

await build({
  entryPoints: ['src/plugin.ts'], bundle: true, external: ['obsidian'],
  platform: 'node', format: 'cjs', target: 'es2020', outfile: 'main.js',
  banner: { js: '/* Obsidian HTML plugin — generated by npm run build */' },
});
await mkdir('plugin/obsidian-html', { recursive: true });
await copyFile('main.js', 'plugin/obsidian-html/main.js');
await copyFile('manifest.json', 'plugin/obsidian-html/manifest.json');
await cp('dist/templates', 'plugin/obsidian-html/templates', { recursive: true });
console.log('Plugin built: plugin/obsidian-html');
